/** 週末或紅字國定假日／補假 → 不推播 */
export function isTaiwanOffDay(now = new Date()): boolean {
  const weekday = getTaipeiWeekday(now) // 0=日 … 6=六
  if (weekday === 0 || weekday === 6) return true
  return TAIWAN_PUBLIC_HOLIDAYS.has(getTaipeiYmd(now))
}
